def parse(path):
    raw = open(path, encoding="utf-8").read()
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", raw, re.S)
    if not m:
        sys.exit(f"{path}: missing front matter")
    meta = {}
    for line in m.group(1).splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            meta[k.strip()] = v.strip()
    for key in ("title", "slug", "description", "date"):
        if not meta.get(key):
            sys.exit(f"{path}: front matter needs '{key}'")
    meta.setdefault("updated", meta["date"])
    body = m.group(2)
    if EM_DASH in raw:
        sys.exit(f"{path}: contains an em dash. Rewrite it with a period, comma or colon.")
    if "Ground App" in raw:
        sys.exit(f"{path}: spell it GroundApp")
    meta["source"] = os.path.basename(path)
    meta["md"] = body
    return meta


def render_md(text):
    out = markdown.markdown(text, extensions=["tables", "sane_lists"], output_format="html")
    out = out.replace("<table>", '<div class="table-wrap"><table>').replace("</table>", "</table></div>")
    # external links open normally; App Store links get no special treatment
    return out


def nice_date(iso):
    d = dt.date.fromisoformat(iso)
    return d.strftime("%B %-d, %Y")


def read_minutes(text):
    words = len(re.findall(r"\w+", text))
    return max(1, round(words / 230))


