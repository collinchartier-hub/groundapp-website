def write(path, text):
    if EM_DASH in text:
        sys.exit(f"refusing to write {path}: contains an em dash")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", os.path.relpath(path, ROOT))


def update_redirects(posts):
    path = os.path.join(SITE, "_redirects")
    existing = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
    lines = [REDIRECT_START]
    for p in posts:
        old = p.get("old")
        if not old:
            continue
        new = f"/blog/{p['slug']}/"
        lines.append(f"/posts/{old}.md {new} 301")
        lines.append(f"/posts/{old} {new} 301")
        lines.append(f"/posts/{old}/ {new} 301")
    lines.append("/posts /blog/ 301")
    lines.append("/posts/ /blog/ 301")
    lines.append(REDIRECT_END)
    block = "\n".join(lines)
    if REDIRECT_START in existing:
        existing = re.sub(re.escape(REDIRECT_START) + r".*?" + re.escape(REDIRECT_END), block, existing, flags=re.S)
    else:
        existing = (existing.rstrip("\n") + "\n\n" if existing.strip() else "") + block + "\n"
    with open(path, "w", encoding="utf-8") as f:
        f.write(existing)
    print("updated", os.path.relpath(path, ROOT))


def main():
    files = sorted(f for f in os.listdir(SRC) if f.endswith(".md"))
    posts = [parse(os.path.join(SRC, f)) for f in files]
    slugs = [p["slug"] for p in posts]
    if len(set(slugs)) != len(slugs):
        sys.exit("duplicate slugs")
    for p in posts:
        write(os.path.join(OUT, p["slug"], "index.html"), post_page(p, posts))
    write(os.path.join(OUT, "index.html"), index_page(posts))
    # remove pages for posts that no longer exist
    for d in os.listdir(OUT):
        full = os.path.join(OUT, d)
        if os.path.isdir(full) and d not in slugs:
            print(f"note: {os.path.relpath(full, ROOT)} has no source post (left in place)")
    update_redirects(posts)


if __name__ == "__main__":
    main()
